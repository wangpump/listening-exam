export const EXAM_END_MS = 2200835;

export function answerLockOffsetMs(questionNumber) {
  const i = Number(questionNumber) - 1;

  if (
    !Number.isInteger(i) ||
    i < 0 ||
    i >= 100
  ) {
    throw new Error(
      'questionNumber must be an integer from 1 to 100'
    );
  }

  return ANSWER_LOCKS_MS[i];
}

export function timelinePosition(elapsedMs) {
  const t = Math.max(
    0,
    Number(elapsedMs) || 0
  );

  if (t < QUESTION_STARTS_MS[0]) {
    return {
      kind: 'initial-prep',
      question: 1,
      section: 1
    };
  }

  if (t >= EXAM_END_MS) {
    return {
      kind: 'finished',
      question: 101,
      section: 5
    };
  }

  let low = 0;
  let high = 99;
  let index = 0;

  while (low <= high) {
    const mid = Math.floor(
      (low + high) / 2
    );

    if (QUESTION_STARTS_MS[mid] <= t) {
      index = mid;
      low = mid + 1;
    } else {
      high = mid - 1;
    }
  }

  const q = index + 1;
  const section = Math.ceil(q / 20);

  if (t < ANSWER_LOCKS_MS[index]) {
    return {
      kind: 'question',
      question: q,
      section
    };
  }

  if (q === 100) {
    return {
      kind: 'question',
      question: q,
      section
    };
  }

  if (q % 20 === 0) {
    return {
      kind: 'section-prep',
      question: q + 1,
      section: section + 1
    };
  }

  return {
    kind: 'gap',
    question: q,
    section
  };
}
